
import { useState } from "react";
import {
  Sparkles,
  FileText,
  Target,
  MessageSquareText,
  Mail,
  Copy,
  Check,
  ArrowRight,
  RotateCcw,
  Lightbulb,
  LoaderCircle,
  ShieldCheck,
} from "lucide-react";
import "./AIAssistant.css";

type ToolId = "resume" | "match" | "interview" | "writing";

type Tool = {
  id: ToolId;
  title: string;
  description: string;
  icon: typeof FileText;
};

const tools: Tool[] = [
  {
    id: "resume",
    title: "Resume Analyzer",
    description: "Find strengths and improve your resume.",
    icon: FileText,
  },
  {
    id: "match",
    title: "Job Match",
    description: "Compare your resume with a job description.",
    icon: Target,
  },
  {
    id: "interview",
    title: "Interview Prep",
    description: "Practise questions for your next interview.",
    icon: MessageSquareText,
  },
  {
    id: "writing",
    title: "Career Writing",
    description: "Draft professional messages and emails.",
    icon: Mail,
  },
];

const interviewExamples = [
  "Walk me through a project you built and the problem it solved.",
  "How would you debug a difficult production issue?",
  "Describe a technical decision you made and the trade-offs involved.",
  "Tell me about a time you received critical feedback.",
  "How do you prioritize tasks when working under a deadline?",
];

const AIAssistant = () => {
  const [activeTool, setActiveTool] = useState<ToolId>("resume");
  const [resumeText, setResumeText] = useState("");
  const [jobDescription, setJobDescription] = useState("");
  const [targetRole, setTargetRole] = useState("");
  const [experience, setExperience] = useState("Entry level");
  const [writingType, setWritingType] = useState("Follow-up email");
  const [company, setCompany] = useState("");
  const [extraContext, setExtraContext] = useState("");
  const [result, setResult] = useState("");
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(false);
  const [copied, setCopied] = useState(false);

  const selectedTool = tools.find((tool) => tool.id === activeTool)!;
  const ActiveIcon = selectedTool.icon;

  const resetResult = () => {
    setResult("");
    setError("");
    setCopied(false);
  };

  const runAssistant = async () => {
    setError("");
    setResult("");
    setCopied(false);

    if (activeTool === "resume" && resumeText.trim().length < 40) {
      setError("Paste your resume text first (at least 40 characters).");
      return;
    }

    if (
      activeTool === "match" &&
      (!resumeText.trim() || !jobDescription.trim())
    ) {
      setError("Enter both your resume and the job description.");
      return;
    }

    if (activeTool === "interview" && !targetRole.trim()) {
      setError("Enter the role you are preparing for.");
      return;
    }

    if (activeTool === "writing" && !company.trim()) {
      setError("Enter the company or recipient name.");
      return;
    }

    setLoading(true);

    try {
      // Demo mode: replace this section with a POST request
      // to your Express API when the backend is ready.
      await new Promise((resolve) => setTimeout(resolve, 700));

      let generated = "";

      if (activeTool === "resume") {
        const words = resumeText.trim().split(/\s+/).length;
        const hasNumbers = /\d/.test(resumeText);
        const hasActionWords =
          /\b(built|developed|created|implemented|improved|designed|led|reduced|increased)\b/i.test(
            resumeText
          );

        generated = `RESUME REVIEW — DEMO MODE

OVERVIEW
Your pasted resume contains approximately ${words} words. This is a basic text-based review, not a complete resume or ATS evaluation.

POTENTIAL STRENGTHS
• You have provided content that can be reviewed for clarity and relevance.
• Your experience and skills can be made easier for recruiters to scan with clear headings and concise bullet points.

AREAS TO CHECK
${hasActionWords ? "• Some action-oriented wording is present. Make sure each claim explains what you personally did." : "• Start experience bullets with clear action verbs such as Built, Developed, Automated, or Improved."}
${hasNumbers ? "• Numbers appear in the text. Check that they provide meaningful, accurate evidence of impact." : "• Add accurate metrics where possible, such as response time reduced, users supported, or time saved."}
• Keep formatting consistent and avoid long paragraphs.
• Put the most relevant skills and experience near the top.

NEXT STEPS
1. Tailor the resume to a specific role.
2. Explain the problem, your contribution, and the outcome for each major project.
3. Verify that every skill and achievement is accurate.

This result was generated by local demo logic, not an AI model.`;
      }

      if (activeTool === "match") {
        const resumeWords = new Set(
          resumeText.toLowerCase().match(/[a-z+#.]+/g) ?? []
        );
        const jdWords =
          jobDescription.toLowerCase().match(/[a-z+#.]+/g) ?? [];
        const keywords = [
          ...new Set(
            jdWords.filter(
              (word) =>
                word.length > 3 &&
                ![
                  "with",
                  "that",
                  "this",
                  "have",
                  "will",
                  "your",
                  "from",
                  "work",
                  "team",
                  "role",
                  "years",
                  "using",
                  "into",
                  "able",
                  "about",
                  "they",
                  "their",
                  "what",
                  "must",
                  "should",
                  "responsibilities",
                  "requirements",
                ].includes(word)
            )
          ),
        ].slice(0, 20);

        const matched = keywords.filter((word) => resumeWords.has(word));
        const missing = keywords.filter((word) => !resumeWords.has(word));

        generated = `JOB MATCH REVIEW — DEMO MODE

TARGET ROLE
${targetRole.trim() || "Role specified in the job description"}

KEYWORD OVERLAP
${matched.length ? matched.join(", ") : "No exact keyword overlap detected by the basic demo checker."}

TERMS TO REVIEW
${missing.length ? missing.join(", ") : "No unmatched keywords in this limited sample."}

RECOMMENDATIONS
• Review the job requirements and identify which ones you can genuinely demonstrate.
• Use relevant terminology naturally where it accurately describes your experience.
• Add evidence from real projects, internships, or coursework.
• Do not add skills or experience you do not have.

IMPORTANT
This is a simple keyword comparison, not a semantic AI match score. A missing word does not necessarily mean a missing skill, and a matching word does not prove proficiency.`;
      }

      if (activeTool === "interview") {
        const questions = interviewExamples
          .map((question, index) => `${index + 1}. ${question}`)
          .join("\n\n");

        generated = `INTERVIEW PRACTICE — DEMO MODE

ROLE
${targetRole}

EXPERIENCE LEVEL
${experience}

PRACTICE QUESTIONS

${questions}

HOW TO PREPARE
• Use specific examples from your own experience.
• Explain the problem, your approach, and the result.
• For technical questions, state your assumptions and discuss trade-offs.
• Practise answering aloud in a concise, structured way.

NEXT STEP
Write your answer to one question, then review it for clarity, evidence, and relevance.

These are sample questions from local demo logic, not AI-generated role-specific questions.`;
      }

      if (activeTool === "writing") {
        const context = extraContext.trim();

        if (writingType === "Follow-up email") {
          generated = `Subject: Following Up on My Application

Dear Hiring Team,

I hope you are doing well.

I am writing to follow up on my application${targetRole.trim() ? ` for the ${targetRole.trim()} position` : ""} at ${company.trim()}. I remain interested in the opportunity and would appreciate any updates you can share regarding the next steps.

${context ? `For context: ${context}\n\n` : ""}Thank you for your time and consideration. I look forward to hearing from you.

Best regards,
[Your Name]`;
        } else if (writingType === "Recruiter message") {
          generated = `Hello,

I came across the ${targetRole.trim() || "opportunity"} at ${company.trim()} and wanted to express my interest.

${context ? `${context}\n\n` : ""}I would appreciate the opportunity to learn more about the role and how my background may be relevant.

Thank you for your time.

Best regards,
[Your Name]`;
        } else if (writingType === "Cover letter") {
          generated = `Dear Hiring Team at ${company.trim()},

I am interested in the ${targetRole.trim() || "open position"} opportunity at ${company.trim()}.

${context || "[Add a brief, truthful summary of your relevant experience, skills, and motivation for applying.]"}

I would welcome the opportunity to discuss how my skills and experience align with the team's needs. Thank you for considering my application.

Best regards,
[Your Name]`;
        } else {
          generated = `Subject: Thank You for the Interview

Dear Hiring Team,

Thank you for taking the time to speak with me about the ${targetRole.trim() || "position"} at ${company.trim()}.

I appreciated learning more about the role and the team. Our conversation strengthened my interest in the opportunity.

${context ? `${context}\n\n` : ""}Thank you again for your time and consideration.

Best regards,
[Your Name]`;
        }
      }

      setResult(generated);
    } catch {
      setError("Something went wrong. Please try again.");
    } finally {
      setLoading(false);
    }
  };

  const copyResult = async () => {
    try {
      await navigator.clipboard.writeText(result);
      setCopied(true);
    } catch {
      setError("Clipboard access failed. Please select and copy the result manually.");
    }
  };

  return (
    <div className="ai-assistant-page">
      <section className="ai-hero">
        <div className="ai-hero-content">
          <span className="ai-hero-eyebrow">
            <Sparkles size={14} /> YOUR PERSONAL CAREER COPILOT
          </span>
          <h1>Meet your AI career assistant.</h1>
          <p>
            Get help improving your resume, matching job descriptions,
            preparing for interviews, and communicating with recruiters.
          </p>
          <div className="ai-hero-note">
            <ShieldCheck size={15} />
            Review every suggestion before using it in an application.
          </div>
        </div>
        <div className="ai-hero-art" aria-hidden="true">
          <div className="ai-orbit orbit-one" />
          <div className="ai-orbit orbit-two" />
          <div className="ai-hero-sparkle">
            <Sparkles size={40} />
          </div>
          <span className="ai-float-icon float-file"><FileText size={20} /></span>
          <span className="ai-float-icon float-target"><Target size={20} /></span>
          <span className="ai-float-icon float-message"><MessageSquareText size={20} /></span>
        </div>
      </section>

      <div className="ai-section-heading">
        <div>
          <h2>Choose your tool</h2>
          <p>What would you like help with today?</p>
        </div>
        <span className="ai-demo-badge">DEMO MODE</span>
      </div>

      <div className="ai-tool-grid">
        {tools.map((tool) => {
          const Icon = tool.icon;

          return (
            <button
              key={tool.id}
              className={`ai-tool-card ${activeTool === tool.id ? "active" : ""}`}
              onClick={() => {
                setActiveTool(tool.id);
                resetResult();
              }}
            >
              <span className="ai-tool-icon"><Icon size={21} /></span>
              <span className="ai-tool-card-copy">
                <strong>{tool.title}</strong>
                <span>{tool.description}</span>
              </span>
              <ArrowRight className="ai-tool-arrow" size={17} />
            </button>
          );
        })}
      </div>

      <div className="ai-workspace">
        <section className="ai-form-panel">
          <div className="ai-panel-heading">
            <span className="ai-active-tool-icon"><ActiveIcon size={20} /></span>
            <div>
              <h2>{selectedTool.title}</h2>
              <p>{selectedTool.description}</p>
            </div>
          </div>

          {activeTool === "resume" && (
            <div className="ai-fields">
              <label>
                Paste your resume text
                <textarea
                  rows={10}
                  value={resumeText}
                  onChange={(event) => setResumeText(event.target.value)}
                  placeholder="Paste the text from your resume here..."
                />
              </label>
              <p className="ai-field-help">
                Demo mode accepts pasted text. PDF and DOCX parsing can be added through the backend later.
              </p>
            </div>
          )}

          {activeTool === "match" && (
            <div className="ai-fields">
              <label>
                Target role (optional)
                <input
                  value={targetRole}
                  onChange={(event) => setTargetRole(event.target.value)}
                  placeholder="e.g. Frontend Developer Intern"
                />
              </label>
              <label>
                Resume text
                <textarea
                  rows={7}
                  value={resumeText}
                  onChange={(event) => setResumeText(event.target.value)}
                  placeholder="Paste your resume text..."
                />
              </label>
              <label>
                Job description
                <textarea
                  rows={7}
                  value={jobDescription}
                  onChange={(event) => setJobDescription(event.target.value)}
                  placeholder="Paste the job description..."
                />
              </label>
            </div>
          )}

          {activeTool === "interview" && (
            <div className="ai-fields">
              <label>
                Target job role
                <input
                  value={targetRole}
                  onChange={(event) => setTargetRole(event.target.value)}
                  placeholder="e.g. Full-Stack Developer"
                />
              </label>
              <label>
                Experience level
                <select
                  value={experience}
                  onChange={(event) => setExperience(event.target.value)}
                >
                  <option>Student</option>
                  <option>Entry level</option>
                  <option>1–3 years</option>
                  <option>3+ years</option>
                </select>
              </label>
              <div className="ai-prep-tip">
                <Lightbulb size={18} />
                <p>Practise explaining your projects, decisions, and lessons learned using specific examples.</p>
              </div>
            </div>
          )}

          {activeTool === "writing" && (
            <div className="ai-fields">
              <label>
                Type of writing
                <select
                  value={writingType}
                  onChange={(event) => setWritingType(event.target.value)}
                >
                  <option>Follow-up email</option>
                  <option>Recruiter message</option>
                  <option>Cover letter</option>
                  <option>Thank-you email</option>
                </select>
              </label>
              <label>
                Company or recipient
                <input
                  value={company}
                  onChange={(event) => setCompany(event.target.value)}
                  placeholder="e.g. Acme Technologies"
                />
              </label>
              <label>
                Target role (optional)
                <input
                  value={targetRole}
                  onChange={(event) => setTargetRole(event.target.value)}
                  placeholder="e.g. Software Engineer Intern"
                />
              </label>
              <label>
                Additional context (optional)
                <textarea
                  rows={5}
                  value={extraContext}
                  onChange={(event) => setExtraContext(event.target.value)}
                  placeholder="Add truthful details about your experience or conversation..."
                />
              </label>
            </div>
          )}

          {error && <p className="ai-error-message">{error}</p>}

          <div className="ai-form-footer">
            <span><ShieldCheck size={14} /> Review results before using them</span>
            <button
              className="ai-generate-button"
              onClick={runAssistant}
              disabled={loading}
            >
              {loading ? (
                <><LoaderCircle className="ai-spin" size={17} /> Generating...</>
              ) : (
                <><Sparkles size={17} /> Generate result <ArrowRight size={16} /></>
              )}
            </button>
          </div>
        </section>

        <section className="ai-result-panel">
          <div className="ai-result-header">
            <div>
              <h2>Your results</h2>
              <p>Your generated output will appear here.</p>
            </div>
            {result && (
              <button className="ai-copy-button" onClick={copyResult}>
                {copied ? <Check size={15} /> : <Copy size={15} />}
                {copied ? "Copied" : "Copy"}
              </button>
            )}
          </div>

          {loading ? (
            <div className="ai-result-empty">
              <LoaderCircle className="ai-spin" size={30} />
              <strong>Working on your result...</strong>
              <span>This demo simulates a short processing delay.</span>
            </div>
          ) : result ? (
            <div className="ai-result-content">
              <span className="ai-result-demo-label">SAMPLE OUTPUT · DEMO</span>
              <pre>{result}</pre>
              <button
                className="ai-reset-button"
                onClick={() => {
                  setResult("");
                  setError("");
                  setCopied(false);
                }}
              >
                <RotateCcw size={14} /> Clear result
              </button>
            </div>
          ) : (
            <div className="ai-result-empty">
              <span className="ai-result-empty-icon"><Sparkles size={26} /></span>
              <strong>Ready when you are</strong>
              <span>Choose a tool, enter your details, and generate a result.</span>
            </div>
          )}
        </section>
      </div>

      <div className="ai-privacy-note">
        <ShieldCheck size={17} />
        <p>
          <strong>Your career information matters.</strong> This prototype processes
          text locally in demo mode. Before adding real AI, resume uploads, or storage,
          configure secure backend processing and clear data-handling rules.
        </p>
      </div>
    </div>
  );
};

export default AIAssistant;
